#!/usr/bin/env python3
"""Generate compact C++ pinyin lookup table from pypinyin.

Output: src/pinyin_table.h
  - kSyllables[] : unique syllables (a-z, v for ü)
  - kCharPinyin[]: {codepoint, syllable index}, sorted by codepoint
"""
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".tools"))
from pypinyin import lazy_pinyin  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "pinyin_table.h")
RE_VALID = re.compile(r"^[a-z]+$")

pairs = []
syllables = set()

for cp in range(0x4E00, 0xA000):
    ch = chr(cp)
    try:
        res = lazy_pinyin(ch)
    except Exception:
        continue
    if not res:
        continue
    py = res[0].lower().replace("ü", "v").replace("u:", "v")
    if not RE_VALID.match(py) or len(py) > 7:
        continue
    pairs.append((cp, py))
    syllables.add(py)

syllables = sorted(syllables)
sidx = {s: i for i, s in enumerate(syllables)}
pairs.sort()

os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("// Auto-generated by tools/gen_pinyin.py. Do not edit.\n")
    f.write("#pragma once\n\n")
    f.write("static const char* const kSyllables[] = {\n")
    for i in range(0, len(syllables), 8):
        f.write("    " + " ".join('"%s",' % s for s in syllables[i:i + 8]) + "\n")
    f.write("};\n\n")
    f.write("struct PyEntry { unsigned short cp; unsigned short idx; };\n")
    f.write("static const PyEntry kCharPinyin[] = {\n")
    for cp, py in pairs:
        f.write("    {0x%04X,%d},\n" % (cp, sidx[py]))
    f.write("};\n")

print("chars=%d syllables=%d size=%dKB" % (
    len(pairs), len(syllables), os.path.getsize(OUT) // 1024))
